def compute_hard_filter_skips(candidates: Iterable[Any], selected_ids: Any) -> dict:
    """``{"ids": [...], "names": [...]}`` of selected rows with an exclusion reason."""
    ids: dict = {}
    names = []
    for c in candidates:
        cid = candidate_row_id(c)
        if not cid or cid not in selected_ids:
            continue
        if get_candidate_exclusion_reason(c):
            ids[cid] = None
            names.append(_or(get_candidate_display_name(c), _get(c, "name"), "Unnamed"))
    return {"ids": list(ids), "names": names}


def select_candidates_missing_contact(
    candidates: Iterable[Any], selected_ids: Any, hard_filter_skip_ids: Any
) -> list:
    """Selected, not hard-filter-skipped rows missing a valid phone OR a valid
    email. Selection is tested with the row's RAW id (an int id never matches a
    set of string ids), exactly as the browser does."""
    out = []
    for c in candidates:
        raw = _or(_get(c, "candidate_id"), _get(c, "jobdiva_candidate_id"), _get(c, "id"))
        if not _set_has(selected_ids, raw):
            continue
        if _js_trim(_s(raw)) in hard_filter_skip_ids:
            continue
        if not is_valid_launch_phone(get_candidate_launch_phone(c)) or not is_valid_launch_email(
            get_candidate_launch_email(c)
        ):
            out.append(c)
    return out


_LINKEDIN_IN_TEXT_RE = re.compile(
    r"https?://(?:www\.)?linkedin\.com/in/[A-Za-z0-9\-_%]+", re.IGNORECASE | re.ASCII
)


def extract_linkedin_from_text(text: Any) -> str:
    raw = _s(text)
    if not raw:
        return ""
    m = _LINKEDIN_IN_TEXT_RE.search(raw)
    return m.group(0) if m else ""


def looks_like_linkedin_profile(url: Any) -> bool:
    return "linkedin.com/in/" in _js_trim(_s(url)).lower()


def resolve_linkedin_url(c: Any) -> str:
    """First of profile_url, linkedin_url, urls.linkedin(_url),
    data.urls.linkedin(_url), or a linkedin.com/in/ link in the résumé, that
    looks like a profile URL."""
    urls = _get(c, "urls")
    d = _get(c, "data")
    durls = _get(d, "urls")
    values = [
        _get(c, "profile_url"),
        _get(c, "linkedin_url"),
        _get(urls, "linkedin"),
        _get(urls, "linkedin_url"),
        _get(durls, "linkedin"),
        _get(durls, "linkedin_url"),
        extract_linkedin_from_text(_or(_get(c, "resume_text"), _get(c, "resumeText"), _get(d, "resume_text"))),
    ]
    for u in (_js_trim(_s(v)) for v in values):
        if u and looks_like_linkedin_profile(u):
            return u
    return ""


def build_enrich_request(c: Any, candidate_id: str, linkedin_url: str, jobdiva_id: Any = None) -> dict:
    """One /candidates/enrich-contact(s) request. Keys the browser leaves
    ``undefined`` are omitted (``jobdiva_id=None`` → omitted)."""
    req: dict = {"candidate_id": candidate_id}
    if jobdiva_id is not None:
        req["jobdiva_id"] = jobdiva_id
    source = _get(c, "source")
    if _truthy(source):
        req["source"] = source
    req["linkedin_url"] = linkedin_url
    req["trigger"] = "launch"
    score = _get(c, "match_score")
    if _is_number(score):
        req["match_score"] = score
    return req


def interpret_enrich_answer(enriched: Any, launchable_now: bool) -> dict:
    """``{"outcome", "lookedUp", "kipplo", "override"?, "phoneProvider"?,
    "emailProvider"?}``; outcome ∈ failed | succeeded | already_reachable |
    not_eligible | no_contact. ``override`` REPLACES the row's own contact."""
    if not _truthy(enriched) or _get(enriched, "status") == "error":
        return {"outcome": "failed", "lookedUp": False, "kipplo": ""}
    looked_up = _get(enriched, "status") == "success"
    kipplo = _s(_get(_get(enriched, "lookup"), "kipplo"))
    next_phone = _or(_get(enriched, "phone"), _get(enriched, "mobilePhone"), "")
    next_email = _or(_get(enriched, "email"), "")
    if _truthy(next_phone) or _truthy(next_email):
        override: dict = {}
        if _truthy(next_phone):
            override["phone"] = next_phone
        if _truthy(next_email):
            override["email"] = next_email
        out = {"outcome": "succeeded", "lookedUp": looked_up, "kipplo": kipplo, "override": override}
        if _truthy(next_phone):
            out["phoneProvider"] = _js_str(_or(_get(enriched, "phone_provider"), "other"))
        if _truthy(next_email):
            out["emailProvider"] = _js_str(_or(_get(enriched, "email_provider"), "other"))
        return out
    if launchable_now:
        return {"outcome": "already_reachable", "lookedUp": looked_up, "kipplo": kipplo}
    outcome = "not_eligible" if _get(enriched, "status") == "skipped" else "no_contact"
    return {"outcome": outcome, "lookedUp": looked_up, "kipplo": kipplo}


# ── DNC re-check, ready / needs-contact split ──────────────────────────────

def _override_field(overrides: Any, cid: str, key: str) -> Any:
    return _get(_get(overrides, cid), key)


def dnc_dropped_ids(candidates: Iterable[Any], selected_ids: Any, overrides: Any, dnc_phones: Any) -> list:
    """Selected ids whose override phone (else TOP-LEVEL ``phone``) is on the DNC list."""
    dropped: dict = {}
    if dnc_phones:
        for c in candidates:
            cid = candidate_row_id(c)
            if not cid or cid not in selected_ids:
                continue
            phone_to_check = _or(_override_field(overrides, cid, "phone"), _get(c, "phone"))
            np = normalize_dnc_phone(phone_to_check)
            if np and np in dnc_phones:
                dropped[cid] = None
    return list(dropped)


def split_ready_needs_contact(
    candidates: Iterable[Any],
    *,
    selected_ids: Any,
    skip_ids: Any,
    overrides: Any,
    jobdiva_id: Any = None,
) -> dict:
    """Ready = a usable phone OR a real email, where a channel is usable only
    if valid AND not shared with another row of this selection (minus
    ``skip_ids`` = DNC + hard-filter skips). A duplicated phone with a unique
    valid email is READY. Duplicate keys: all phone digits, lower-cased email.
    Returns ``{"readyIds", "needsInfo", "duplicateEmailIds", "duplicatePhoneIds"}``.
    """
    rows = list(candidates)
    email_to_ids: dict = {}
    phone_to_ids: dict = {}

    def effective(c: Any, cid: str) -> tuple:
        phone = _or(_override_field(overrides, cid, "phone"), get_candidate_launch_phone(c))
        email = _js_trim(_js_str(_or(_override_field(overrides, cid, "email"),
                                     get_candidate_launch_email(c)))).lower()
        return phone, email

    def in_scope(cid: str) -> bool:
        return bool(cid) and cid in selected_ids and cid not in skip_ids

    for c in rows:
        cid = candidate_row_id(c)
        if not in_scope(cid):
            continue
        phone, email = effective(c, cid)
        if is_valid_launch_email(email):
            email_to_ids.setdefault(email, []).append(cid)
        if is_valid_launch_phone(phone):
            phone_to_ids.setdefault(launch_phone_digits(phone), []).append(cid)
    dup_email: dict = {}
    dup_phone: dict = {}
    for ids in email_to_ids.values():
        if len(ids) >= 2:
            dup_email.update(dict.fromkeys(ids))
    for ids in phone_to_ids.values():
        if len(ids) >= 2:
            dup_phone.update(dict.fromkeys(ids))

    ready: dict = {}
    needs_info = []
    for c in rows:
        cid = candidate_row_id(c)
        if not in_scope(cid):
            continue
        phone, email = effective(c, cid)
        phone_ok = is_valid_launch_phone(phone) and cid not in dup_phone
        email_ok = is_valid_launch_email(email) and cid not in dup_email
        if phone_ok or email_ok:
            ready[cid] = None
            continue
        entry = {
            "candidate_id": cid,
            "name": _or(get_candidate_display_name(c), _get(c, "name"), "Unnamed"),
            "headline": _or(_get(c, "title"), _get(c, "headline"), ""),
            "location": _or(_get(c, "location"), ""),
            "source": _or(_get(c, "source"), ""),
        }
        if _truthy(jobdiva_id):
            entry["jobdiva_id"] = _js_str(jobdiva_id)
        entry["needsPhone"] = not phone_ok
        entry["needsEmail"] = not email_ok
        entry["currentPhone"] = _or(phone, "")
        entry["currentEmail"] = _or(email, "")
        needs_info.append(entry)
    return {
        "readyIds": list(ready),
        "needsInfo": needs_info,
        "duplicateEmailIds": list(dup_email),
        "duplicatePhoneIds": list(dup_phone),
    }


def merge_contact_overrides(pending: dict, provided: dict) -> dict:
    """Needs-contact answers over the pending (lookup) overrides: a field left
    empty keeps the pending value (``vals.x || pending[id]?.x``)."""
    merged = dict(pending or {})
    for cid, vals in (provided or {}).items():
        prev = _get(pending, cid)
        entry: dict = {}
        for key in ("phone", "email"):
            v = _get(vals, key)
            if _truthy(v):
                entry[key] = v
            elif isinstance(prev, dict) and key in prev:
                entry[key] = prev[key]
        merged[cid] = entry
    return merged


# ── /candidates/save payload ───────────────────────────────────────────────

def _override_lookup(overrides: dict, raw_id: Any) -> Any:
    if raw_id is None:
        return None
    return overrides.get(_js_str(raw_id))


def apply_contact_overrides(candidates: list, overrides: Optional[dict]) -> list:
    """Overrides REPLACE the row's top-level phone / email (``override.x || c.x``).
    ``overrides=None`` returns ``candidates`` itself."""
    if overrides is None:
        return candidates
    out = []
    for c in candidates:
        raw = _or(_get(c, "candidate_id"), _get(c, "jobdiva_candidate_id"), _get(c, "id"))
        ov = _override_lookup(overrides, raw)
        if not _truthy(ov) or not isinstance(c, dict):
            out.append(c)
            continue
        nc = dict(c)
        for key in ("phone", "email"):
            v = _get(ov, key)
            if _truthy(v):
                nc[key] = v
            elif key not in c:
                nc.pop(key, None)
        out.append(nc)
    return out


def select_save_candidates(effective: Iterable[Any], *, launch_ids: Any, job: Any, dnc_phones: Any) -> list:
    """Rows /candidates/save persists: in ``launch_ids`` (raw or String() id),
    no exclusion reason, not ``no_contact``, not a hiring-client conflict, and
    TOP-LEVEL phone not on the DNC list."""
    out = []
    for c in effective:
        raw = _or(_get(c, "candidate_id"), _get(c, "jobdiva_candidate_id"), _get(c, "id"))
        if not (_set_has(launch_ids, raw) or (raw is not None and _js_str(raw) in launch_ids)):
            continue
        if get_candidate_exclusion_reason(c):
            continue
        if _get(c, "no_contact") is True:
            continue
        if _get(with_client_conflict_flag(c, job), "client_conflict") is True:
            continue
        if dnc_phones:
            np = normalize_dnc_phone(_get(c, "phone"))
            if np and np in dnc_phones:
                continue
        out.append(c)
    return out


def _list_or_empty(v: Any) -> list:
    return v if isinstance(v, list) else []


def _dict_or(v: Any, default: Any) -> Any:
    return v if isinstance(v, dict) else default


def build_save_candidate_payload(c: Any) -> dict:
    """One /candidates/save row, exactly as the browser builds it."""
    display_name = get_candidate_display_name(c)
    launch_email = get_candidate_launch_email(c)
    launch_phone = get_candidate_launch_phone(c)
    skills = _get(c, "skills")
    if isinstance(skills, list):
        skill_list = skills
    elif isinstance(skills, str) and _js_trim(skills):
        try:
            parsed = _json_parse(skills)
            skill_list = parsed if isinstance(parsed, list) else [skills]
        except (ValueError, RecursionError):
            skill_list = [skills]
    else:
        skill_list = []
    score = _get(c, "match_score")
    # JSON.stringify writes NaN / ±Infinity as null.
    score = score if _is_number(score) and math.isfinite(score) else None
    jd = _get(c, "jobdiva_candidate_id")
    ei = _get(c, "enhanced_info")
    urls = _get(c, "urls")
    return {
        "candidate_id": _js_str(_or(_get(c, "candidate_id"), _get(c, "jobdiva_candidate_id"),
                                    _get(c, "id"), "unknown")),
        "name": _or(display_name, "Unnamed Candidate"),
        "email": launch_email if is_valid_launch_email(launch_email) else None,
        "phone": launch_phone if is_valid_launch_phone(launch_phone) else None,
        "skills": skill_list,
        "experience_years": _or(_get(c, "yearsExtracted"), _get(c, "experience_years"), 0),
        "source": _or(_get(c, "source"), "JobDiva-Applicants"),
        "jobdiva_candidate_id": _js_str(jd) if _truthy(jd) else None,
        "headline": _or(_get(c, "title"), _get(c, "headline"), ""),
        "location": _or(_get(c, "location"), ""),
        "profile_url": _or(_get(c, "profile_url"), None),
        "image_url": _or(_get(c, "image_url"), None),
        "resume_text": _or(_get(c, "resume_text"), _get(c, "resumeText"), ""),
        "resume_id": _js_str(_or(_get(c, "resumeId"), _get(c, "resume_id"), "")),
        "is_selected": True,
        "education": _list_or_empty(_or(_get(c, "education"), _get(c, "candidate_education"))),
        "certifications": _list_or_empty(_or(_get(c, "certifications"), _get(c, "candidate_certification"))),
        "company_experience": _list_or_empty(_or(_get(c, "company_experience"), _get(ei, "company_experience"))),
        "urls": urls if isinstance(urls, dict) else _or(_get(ei, "urls"), {}),
        "match_score": score,
        "detail_failed": _truthy(_get(c, "detail_failed")),
        "matched_skills": _list_or_empty(_get(c, "matched_skills")),
        "missing_skills": _list_or_empty(_get(c, "missing_skills")),
        "match_score_details": _dict_or(_get(c, "match_score_details"), {}),
        "explainability": _list_or_empty(_get(c, "explainability")),
        "enhanced_info": _dict_or(ei, None),
        "linkedin_profile": _dict_or(_get(c, "linkedin_profile"), None),
    }


def build_launch_save_payload(
    candidates: list,
    *,
    launch_ids: Any,
    overrides: Optional[dict] = None,
    job: Any = None,
    dnc_phones: Any = (),
) -> list:
    """apply_contact_overrides → select_save_candidates → build_save_candidate_payload."""
    effective = apply_contact_overrides(candidates, overrides)
    selected = select_save_candidates(effective, launch_ids=launch_ids, job=job, dnc_phones=dnc_phones)
    return [build_save_candidate_payload(c) for c in selected]


# ── Search stream parser ───────────────────────────────────────────────────

_SEARCHING_AT_RE = re.compile("^Searching at[" + _WS + "]*", re.IGNORECASE | re.ASCII)
_ELLIPSIS_END_RE = re.compile(r"\.\.\.\Z")


def map_stage_to_status(stage: str) -> str:
    raw = _s(stage).lower()
    if "exa deep-search" in raw:
        return stage
    if "jobdiva applicants" in raw:
        return "Searching at JobDiva portal (Applicants)..."
    if "jobdiva talent" in raw:
        return "Searching at JobDiva portal (Talent Search)..."
    if "linkedin" in raw:
        return "Searching at LinkedIn portal..."
    if "exa" in raw:
        return "Searching at Exa portal..."
    if "dice" in raw:
        return "Searching at Dice portal..."
    return stage


def stage_portal(mapped: str) -> str:
    if "portal" not in mapped.lower():
        return ""
    return _js_trim(_ELLIPSIS_END_RE.sub("", _SEARCHING_AT_RE.sub("", mapped, count=1), count=1))


def found_profiles_status(found_count: int, active_portal: str) -> Optional[str]:
    if found_count == 1:
        return f"Found 1 profile from {active_portal}. Matching resumes against the rubric..."
    if found_count % 5 == 0:
        return f"Found {found_count} profiles from {active_portal}. Matching resumes against the rubric..."
    return None


def _first_truthy_str(row: Any, keys: tuple) -> str:
    """``String(row.a || row.b || ... || "")`` (hot path of the stream parser)."""
    if not isinstance(row, dict):
        return ""
    for key in keys:
        v = row.get(key)
        if v.__class__ is str:
            if v:
                return v
        elif _truthy(v):
            return _js_str(v)
    return ""


_STREAM_CANDIDATE_ID_KEYS = ("candidate_id", "id")
_STREAM_ROW_ID_KEYS = ("candidate_id", "jobdiva_candidate_id", "id")


def stream_candidate_id(data: Any) -> str:
    """A ``candidate`` event's id (the seen-set / runList key)."""
    return _first_truthy_str(data, _STREAM_CANDIDATE_ID_KEYS)


def stream_row_id(c: Any) -> str:
    """The id a ``candidate_detail`` patch / ``dropped`` targets table rows by."""
    return _first_truthy_str(c, _STREAM_ROW_ID_KEYS)


def is_detail_failed_patch(patch: Any) -> bool:
    return _get(patch, "detail_failed") is True or _s(_get(patch, "enhanced_info_status")) in (
        "kept_no_resume", "error",
    )


def apply_stream_patch(c: dict, patch: dict) -> dict:
    """``{...row, ...patch}`` with the phone downgrade guard."""
    merged = {**c, **patch}
    if "phone" in patch:
        merged["phone"] = better_phone_ui(c.get("phone"), patch.get("phone"))
    return merged


def add_stream_candidate(
    rows: list, data: dict, keys_cache: Optional[dict] = None, absorbed: Optional[dict] = None,
) -> list:
    return deduplicate_candidates_ui(rows + [data], keys_cache, absorbed)


def patch_stream_candidates(
    rows: list, target_id: str, patch: dict, keys_cache: Optional[dict] = None, absorbed: Optional[dict] = None,
) -> list:
    return deduplicate_candidates_ui(
        [apply_stream_patch(c, patch) if stream_row_id(c) == target_id else c for c in rows], keys_cache, absorbed,
    )


def drop_stream_candidate(rows: list, target_id: str) -> list:
    return [c for c in rows if stream_row_id(c) != target_id]


def merge_source_status(prev: dict, status: Any) -> dict:
    """``"ok"`` is sticky within a run."""
    src = _s(_get(status, "source"))
    if not src:
        return prev
    if _get(prev.get(src), "status") == "ok" and _get(status, "status") != "ok":
        return prev
    return {**prev, src: status}


def initial_stream_state() -> dict:
    """The parser's state (TS ``StreamState``). ``candidates`` = the Step-5
    table (de-duplicated after every row / patch); ``runList`` = the current
    attempt's rows — the relaxation loop's ``accumulated`` is every attempt's
    runList concatenated, and ``count_qualified`` runs on that."""
    return {
        "candidates": [],
        "seenIds": [],
        "runList": [],
        "sourceStatuses": {},
        "searchStatus": "Connecting to source portals...",
        "activePortal": "source portal",
        "jobdivaCriteriaUnconfigured": False,
        "criteriaModalRequested": False,
        "detailFailedIds": [],
        "errors": [],
    }


def begin_stream_attempt(state: dict, mode: str) -> dict:
    """A /candidates/search response started. ``"replace"`` (first attempt)
    clears the table, seen ids and source statuses; ``"append"`` (relaxation)
    keeps them. Both start a new runList."""
    nxt = {**state, "runList": [], "activePortal": "source portal"}
    if mode == "replace":
        nxt["candidates"] = []
        nxt["sourceStatuses"] = {}
        nxt["seenIds"] = []
    return nxt


def _as_patch(p: Any) -> dict:
    if isinstance(p, dict):
        return p
    if isinstance(p, list):  # an array spreads as its index keys
        return {str(i): v for i, v in enumerate(p)}
    return {}


def apply_stream_event(
    state: dict, event: Any, keys_cache: Optional[dict] = None, absorbed: Optional[dict] = None,
) -> dict:
    """One /candidates/search NDJSON event, exactly as the browser applies it
    (``applyStreamEvent``). Returns a new state; the input is not mutated.
    Without a ``keys_cache`` every event recomputes every row's de-dup keys
    (~5 ms/event at ~1k rows); use ``StreamRun``, which owns the cache (and
    the ``absorbed`` map, see ``deduplicate_candidates_ui``), rather than
    calling this directly.

    * ``candidate``: skipped entirely when its id was already seen this run;
      else appended to runList and the table (de-duplicated).
    * ``candidate_detail`` stage ``dropped``: removes the row and FORGETS the
      id, so a later attempt re-adds it as a new row.
    * any other ``candidate_detail`` (any stage or none — hydration,
      merge-into-owner, exa_deep_search, gender, scored ...): a non-empty patch
      is merged into every table row with that id and the first runList row,
      then de-dup. The last ``scored`` patch wins.
    * ``stage`` / ``summary`` / ``source_status`` (``ok`` sticky) / ``error``
      (recorded; the run keeps going).
    """
    if not isinstance(event, dict):
        return state
    etype = event.get("type")
    if etype == "candidate":
        data = event.get("data")
        if not isinstance(data, dict):
            return state
        cid = stream_candidate_id(data)
        if cid and cid in state["seenIds"]:
            return state
        nxt = dict(state)
        if cid:
            nxt["seenIds"] = state["seenIds"] + [cid]
        nxt["runList"] = state["runList"] + [data]
        nxt["candidates"] = add_stream_candidate(state["candidates"], data, keys_cache, absorbed)
        status = found_profiles_status(len(nxt["runList"]), state["activePortal"])
        if status is not None:
            nxt["searchStatus"] = status
        return nxt
    if etype == "candidate_detail":
        target_id = _s(event.get("candidate_id"))
        stage = _s(event.get("stage"))
        if not target_id:
            return state
        if stage == "dropped":
            return {
                **state,
                "runList": [r for r in state["runList"] if stream_candidate_id(r) != target_id],
                "seenIds": [s for s in state["seenIds"] if s != target_id],
                "candidates": drop_stream_candidate(state["candidates"], target_id),
            }
        patch = _as_patch(event.get("patch"))
        if not patch:
            return state
        nxt = dict(state)
        if is_detail_failed_patch(patch) and target_id not in state["detailFailedIds"]:
            nxt["detailFailedIds"] = state["detailFailedIds"] + [target_id]
        run_list = list(state["runList"])
        for i, r in enumerate(run_list):
            if stream_candidate_id(r) == target_id:
                run_list[i] = apply_stream_patch(r, patch)
                break
        nxt["runList"] = run_list
        nxt["candidates"] = patch_stream_candidates(state["candidates"], target_id, patch, keys_cache, absorbed)
        return nxt
    if etype == "stage":
        mapped = map_stage_to_status(_s(event.get("data")))
        return {**state, "activePortal": stage_portal(mapped) or state["activePortal"], "searchStatus": mapped}
    if etype == "summary":
        data = event.get("data")
        summary = _or(_get(data, "summary"), data, {})
        unconfigured = _truthy(_get(summary, "jobdiva_criteria_unconfigured"))
        return {
            **state,
            "searchStatus": f"Found {len(state['runList'])} profiles. Finalizing shortlist and quality scoring...",
            "jobdivaCriteriaUnconfigured": unconfigured,
            "criteriaModalRequested": state["criteriaModalRequested"] or unconfigured,
        }
    if etype == "source_status":
        status = _or(event.get("data"), {})
        if not _s(_get(status, "source")):
            return state
        return {
            **state,
            "sourceStatuses": merge_source_status(state["sourceStatuses"], status),
            "jobdivaCriteriaUnconfigured": True if _truthy(_get(status, "criteria_unconfigured"))
            else state["jobdivaCriteriaUnconfigured"],
        }
    if etype == "error":
        message = event.get("message")
        return {**state, "errors": state["errors"] + ["" if message is None else _js_str(message)]}
    return state


class StreamRun:
    """One server-side sourcing run (every relaxation attempt): the S1 entry
    point for the reducer above.

    Owns what the browser keeps across ``runSearchStream`` calls: the reducer
    ``state`` (``table`` = the de-duplicated Step-5 rows), every attempt's
    runList (``accumulated`` — what ``qualified`` and ``selection_pool``
    read), the de-dup key cache (so every event takes the fast path) and the
    ``absorbed`` merge map.

    CPU-bound and not thread-safe: ~1 ms per event at ~1k rows, so apply
    events from ONE thread at a time and off the event loop —
    ``await asyncio.to_thread(run.apply_many, batch)`` per flushed batch.
    Rows in ``table`` / ``accumulated`` are shared with the key cache: treat
    them as read-only (copy before changing one).
    """

    def __init__(self) -> None:
        self.state = initial_stream_state()
        self.attempts = 0
        self._prior_rows: list = []  # runLists of the finished attempts
        self._keys_cache: dict = {}
        self._absorbed: dict = {}

    def begin_attempt(self) -> None:
        """An attempt's search started streaming (the browser: the response
        was OK). The first attempt replaces the table, later ones append
        (handleRunSearch); an attempt that never streamed is not begun."""
        if self.attempts:
            self._prior_rows.extend(self.state["runList"])
        self.state = begin_stream_attempt(self.state, "append" if self.attempts else "replace")
        self.attempts += 1

    def apply(self, event: Any) -> None:
        self.state = apply_stream_event(self.state, event, self._keys_cache, self._absorbed)

    def apply_many(self, events: Iterable[Any]) -> None:
        for event in events:
            self.apply(event)

    @property
    def table(self) -> list:
        return self.state["candidates"]

    @property
    def accumulated(self) -> list:
        """The browser's ``accumulated``: every attempt's runList, in order."""
        return self._prior_rows + self.state["runList"]

    def qualified(self, threshold: float = QUALIFIED_SCORE_THRESHOLD) -> int:
        """The relaxation loop's stop count (see ``count_qualified``)."""
        return count_qualified(self.accumulated, threshold)

    def selection_pool(self) -> list:
        """What Source & Launch selects from (see ``choose_selection_pool``)."""
        return choose_selection_pool(self.table, self.accumulated)

    def absorbed(self) -> dict:
        """``loser id → survivor id`` for every row merged away and not back
        in the table (see ``resolve_absorbed``)."""
        return resolve_absorbed(self._absorbed, self.table)
