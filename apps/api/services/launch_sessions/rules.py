_COMPANY_FILLER_RE = re.compile(
    r"\b(inc|llc|ltd|corp|corporation|co|company|plc|gmbh|na|pvt|private|limited|technologies"
    r"|technology|solutions|consulting|services|group|holdings)\b",
    re.ASCII,
)
_HEADLINE_AT_RE = re.compile(
    "(?:[" + _WS + "]+at[" + _WS + "]+|[" + _WS + "]+@[" + _WS + "]*)([^|,;\u2022\xb7(\u2013\u2014]+)",
    re.IGNORECASE | re.ASCII,
)
_LEADING_THE_RE = re.compile("^the[" + _WS + "]+", re.IGNORECASE | re.ASCII)
_TRAILING_JUNK_RE = re.compile("[" + _WS + ".!\\-\u2013\u2014]+\\Z")
_PRESENT_RE = re.compile("present|current", re.IGNORECASE | re.ASCII)


def normalize_company_name(s: Any) -> str:
    x = _s(s).lower()
    x = re.sub(r"[.,]", " ", x)
    x = _COMPANY_FILLER_RE.sub(" ", x)
    x = re.sub(r"[^a-z0-9 ]", " ", x)
    x = _WS_RUN_RE.sub(" ", x)
    return _js_trim(x)


def extract_company_from_headline(headline: Any) -> str:
    """The LAST "at X" / "@ X" of a LinkedIn-style headline."""
    text = _js_trim(_s(headline))
    if not text or _js_len(text) > 300:
        return ""
    matches = list(_HEADLINE_AT_RE.finditer(text))
    if not matches:
        return ""
    company = _js_trim(matches[-1].group(1) or "")
    company = _LEADING_THE_RE.sub("", company, count=1)
    company = _TRAILING_JUNK_RE.sub("", company)
    if not company or len(_WS_RUN_RE.split(company)) > 6:
        return ""
    return company


def _first_list(*vals: Any) -> list:
    for v in vals:
        if isinstance(v, list):
            return v
    return []


def get_candidate_current_companies(c: Any) -> list:
    """Every CURRENT-employer signal (flat fields, current experience entries,
    exa_recent_companies, headline parse), de-duplicated in order."""
    ei = _or(_get(c, "enhanced_info"), _get(_get(c, "data"), "enhanced_info"), {})
    data = _or(_get(c, "data"), {})
    out = []
    for direct in (
        _get(c, "current_company"), _get(ei, "current_company"), _get(data, "current_company"),
        _get(c, "company"), _get(c, "company_name"), _get(ei, "company"),
    ):
        if _truthy(direct) and _js_trim(_js_str(direct)):
            out.append(_js_trim(_js_str(direct)))
    exp_lists = (
        _first_list(_get(c, "company_experience"), _get(ei, "company_experience"),
                    _get(data, "company_experience")),
        _first_list(_get(c, "exa_recent_companies"), _get(data, "exa_recent_companies")),
    )
    for exp in exp_lists:
        for e in exp:
            # Arrays are JS objects too, but carry none of these fields.
            if not isinstance(e, dict):
                continue
            end_val = next(
                (v for v in (e.get("end_date"), e.get("endDate"), e.get("to"), e.get("end")) if v is not None),
                "",
            )
            end_raw = _js_trim(_js_str(end_val))
            is_current = (
                e.get("is_current") is True
                or e.get("current") is True
                or not end_raw
                or bool(_PRESENT_RE.search(end_raw))
            )
            comp = _js_trim(_s(_or(e.get("company"), e.get("company_name"), e.get("employer"), e.get("name"))))
            if is_current and comp:
                out.append(comp)
    for headline in (_get(c, "headline"), _get(c, "title"), _get(data, "headline"), _get(data, "title")):
        parsed = extract_company_from_headline(headline)
        if parsed:
            out.append(parsed)
    return _unique(out)


def _client_of(job: Any) -> Any:
    return _or(_get(job, "customer_name"), _get(job, "customer"), "")


def is_employed_by_client(c: Any, job: Any) -> bool:
    """``job`` = the monitored job; its customer_name / customer is the client."""
    client = normalize_company_name(_client_of(job))
    # "external" is the placeholder for non-JobDiva reqs — never a real client.
    if not client or client == "external":
        return False
    for raw in get_candidate_current_companies(c):
        cand = normalize_company_name(raw)
        if not cand:
            continue
        if cand == client:
            return True
        shorter = cand if len(cand) <= len(client) else client
        if len(shorter) >= 4 and (client in cand or cand in client):
            return True
    return False


def get_candidate_exclusion_reason(c: Any) -> str:
    """"" when launchable, else why not (offer status, placed/hired, Pyramid
    current employee / unavailable). The hiring-client conflict is NOT a reason
    here (see with_client_conflict_flag)."""
    if not _truthy(c):
        return ""
    ei = _or(_get(c, "enhanced_info"), _get(_get(c, "data"), "enhanced_info"), {})
    data = _or(_get(c, "data"), c)

    offer_status = _s(_or(_get(c, "offer_status"), _get(data, "offer_status"))).lower()
    if "offer accepted" in offer_status:
        return "Offer Accepted"
    if "offer extended" in offer_status:
        return "Offer Extended"

    action_types = _or(_get(c, "action_types"), _get(data, "action_types"), [])
    if isinstance(action_types, list):
        for at in action_types:
            at_low = _js_str(at).lower()
            if "offer accepted" in at_low or at_low in ("placed", "hired"):
                return "Offer Accepted"
            if "offer extended" in at_low:
                return "Offer Extended"

    c_avail = _get(c, "available")
    d_avail = _get(data, "available")
    if (
        c_avail is False
        or d_avail is False
        or (c_avail is not None and _js_str(c_avail).lower() == "false")
        or (d_avail is not None and _js_str(d_avail).lower() == "false")
    ):
        return "Current Employee (Pyramid / Unavailable)"

    quals = _or(_get(data, "qualifications"), _get(c, "qualifications"), _get(ei, "qualifications"),
                _get(_get(c, "data"), "qualifications"), [])
    if isinstance(quals, list):
        for q in quals:
            if not isinstance(q, dict):
                continue
            # camelCase (some sources) and UPPERCASE (the BI endpoint).
            q_val = " ".join(_s(q.get(k)) for k in (
                "qualificationValue", "QUALVALUE", "value", "name", "QUALNAME")).lower()
            if "current employee" in q_val:
                return "Current Employee (Pyramid)"
            if "offer extended" in q_val or "offer - extended" in q_val:
                return "Offer Extended"
            if "offer accepted" in q_val or "offer - accepted" in q_val or q_val in ("placed", "hired"):
                return "Offer Accepted"

    # JobDiva API: status=1 means Current Employee, status=2 means Past Employee.
    num_status = _get(c, "status")
    if num_status is None:
        num_status = _get(data, "status")
    if (_is_number(num_status) and num_status == 1) or num_status == "1":
        return "Current Employee (Pyramid)"

    for st in (
        _s(_get(c, "employee_status")), _s(_get(data, "employee_status")),
        _s(_get(c, "available")), _s(_get(data, "available")),
        _s(_get(c, "availability_status")), _s(_get(data, "availability_status")),
    ):
        if not st:
            continue
        st_lower = st.lower()
        if "offer extended" in st_lower or "offer - extended" in st_lower:
            return "Offer Extended"
        if "offer accepted" in st_lower or "offer - accepted" in st_lower or st_lower in ("placed", "hired"):
            return "Offer Accepted"
        if "current employee" in st_lower:
            return "Current Employee (Pyramid)"

    for raw in get_candidate_current_companies(c):
        curr = normalize_company_name(raw)
        if curr and "pyramid" in curr:
            return "Current Employee (Pyramid)"
    return ""


def with_client_conflict_flag(c: Any, job: Any) -> Any:
    """Fallback for rows the backend never stamped: flag a current employee of
    the hiring client. A row that already carries ``client_conflict`` (any
    value, including null) is returned untouched."""
    if not _truthy(c) or not isinstance(c, dict) or "client_conflict" in c:
        return c
    if not is_employed_by_client(c, job):
        return c
    out = dict(c)
    out["client_conflict"] = True
    out["client_conflict_relation"] = "current"
    client = _or(_get(job, "customer_name"), _get(job, "customer"), "client")
    out["client_conflict_reason"] = f"Current employer is the hiring client ({_js_str(client)})"
    return out


# ── Auto-launch selection ───────────────────────────────────────────────────

def is_launch_eligible_score(score: Any) -> bool:
    """A NUMBER (never a bool) at or above the floor; unscored never clears it."""
    return _is_number(score) and math.isfinite(score) and score >= LAUNCH_MIN_SCORE


def clamp_launch_count(n: Any) -> int:
    x = _js_to_number(n)
    if x != x:
        return 0  # TS: NaN, which slices to 0
    if x == math.inf:
        return AUTO_LAUNCH_MAX_COUNT
    if x == -math.inf:
        return 1
    return min(AUTO_LAUNCH_MAX_COUNT, max(1, math.floor(x)))


def count_qualified(rows: Iterable[Any], threshold: float = QUALIFIED_SCORE_THRESHOLD) -> int:
    """``(c.match_score || 0) >= threshold`` — the relaxation loop's stop test.

    Parity input = the browser's ``accumulated``: EVERY attempt's runList
    concatenated (``StreamRun.accumulated`` / ``StreamRun.qualified``), each
    row with the patches of the attempt that streamed it. It therefore counts
    excluded / no-contact / already-launched rows and rows a LATER attempt
    dropped, and string scores coerce ("75" counts). Counting the
    de-duplicated table, or only numeric scores, is not parity.
    """
    return sum(1 for c in rows if _js_to_number(_or(_get(c, "match_score"), 0)) >= threshold)


def candidate_row_id(c: Any) -> str:
    """The id selection / launch / the split key a row by (trimmed)."""
    return _js_trim(_s(_or(_get(c, "candidate_id"), _get(c, "jobdiva_candidate_id"), _get(c, "id"))))


def launched_key(c: Any, cid: str) -> str:
    """``${c.source ?? ""}:${id}``."""
    src = _get(c, "source")
    return f"{'' if src is None else _js_str(src)}:{cid}"


def choose_selection_pool(table: list, accumulated: list) -> list:
    """The rows Source & Launch selects from after a full search
    (``chooseSelectionPool``): the de-duplicated table, unless it is SHORTER
    than ``accumulated`` (every attempt's runList) — which happens whenever a
    cross-source de-dup merge or a later-attempt ``dropped`` ran — and then
    the per-attempt rows: each row's score from the attempt that streamed it
    (not a later relaxed ``scored`` patch), and both copies of a merged person.

    Parity therefore means: select from this pool, then run every later stage
    (lookup, split, save, launch) on TABLE rows whose id was selected — a
    selected id that was merged away launches nobody, and the table copy's
    sticky ``no_contact`` / ``client_conflict`` still blocks it at save.
    Selecting from the table alone is a deliberate divergence: it uses the
    last (relaxed) score, so it can launch rows the browser leaves out.
    """
    return table if len(table) >= len(accumulated) else accumulated


def compute_auto_launch_selection(
    pool: Iterable[Any],
    *,
    launched_keys: Any,
    launched_ids: Any,
    limit: Any = AUTO_LAUNCH_DEFAULT_COUNT,
    min_score: Any = LAUNCH_MIN_SCORE,
    blocked: Optional[dict] = None,
    with_reasons: bool = False,
) -> dict:
    """Best ``limit`` launchable rows at/above the floor (``computeAutoLaunchSelection``).

    Returns ``{"ids", "eligibleTotal", "belowFloor", "unscored"}`` (+
    ``"skipped"`` with ``with_reasons``). Checks, in order, per row: no id
    (ignored), an id already taken (``duplicate_id``), an exclusion reason
    (``exclusion:<reason>``), ``no_contact``, ``launched`` (``source:id`` key
    or bare id — twins included via ``launched_sets_from_response``), then
    ``blocked[id]`` (the caller's reason, e.g. ``in_flight`` /
    ``applicant_backlog``), then the floor (``unscored`` / ``below_floor``).
    A row skipped before the floor does not take its id, so a later copy can
    still be selected. Eligible rows are ranked by score (ties keep pool
    order) and capped; the rest are ``over_limit``. ``skipped`` lists
    ``{"id", "reason"}`` in pool order, then the over-limit rows in rank order.

    * ``limit`` ALWAYS goes through ``clamp_launch_count``: ``None`` / ``0``
      select ONE row (TS parity: ``Math.floor(null)`` is 0, raised to 1). Pass
      the session's real launch count (``AUTO_LAUNCH_DEFAULT_COUNT`` when the
      input has none), never a missing value.
    * ``min_score``: the floor (default ``LAUNCH_MIN_SCORE``). ``None`` = no
      floor (the QA quick launch / a provided selection): every row that
      clears the skips is eligible, unscored ones ranked last (as score -1),
      and ``belowFloor`` / ``unscored`` stay 0.
    """
    floor = None if min_score is None else _js_to_number(min_score)
    eligible = []
    seen: set = set()
    skipped: list = []
    below_floor = 0
    unscored = 0
    for c in pool:
        cid = candidate_row_id(c)
        if not cid:
            continue
        if cid in seen:
            reason = "duplicate_id"
        else:
            exclusion = get_candidate_exclusion_reason(c)
            if exclusion:
                reason = f"exclusion:{exclusion}"
            elif _get(c, "no_contact") is True:
                reason = "no_contact"
            elif launched_key(c, cid) in launched_keys or cid in launched_ids:
                reason = "launched"
            else:
                block = blocked.get(cid) if blocked else None
                reason = _js_str(block) if _truthy(block) else ""
        if reason:
            if with_reasons:
                skipped.append({"id": cid, "reason": reason})
            continue
        seen.add(cid)
        score = _get(c, "match_score")
        if floor is None:
            eligible.append((cid, score if _is_number(score) else -1))
            continue
        if not _is_number(score):
            unscored += 1
            reason = "unscored"
        elif not (math.isfinite(score) and score >= floor):
            below_floor += 1
            reason = "below_floor"
        else:
            eligible.append((cid, score))
            continue
        if with_reasons:
            skipped.append({"id": cid, "reason": reason})
    ranked = sorted(eligible, key=lambda e: -e[1])
    cap = clamp_launch_count(limit)
    out = {
        "ids": [cid for cid, _ in ranked[:cap]],
        "eligibleTotal": len(eligible),
        "belowFloor": below_floor,
        "unscored": unscored,
    }
    if with_reasons:
        skipped.extend({"id": cid, "reason": "over_limit"} for cid, _ in ranked[cap:])
        out["skipped"] = skipped
    return out


def launched_sets_from_response(items: Optional[Iterable[Any]]) -> dict:
    """``launched-candidate-keys`` items → ``{"keys": set, "ids": set}``; a stamped
    ``jobdiva_candidate_id`` (the provisioned twin) counts as a launched id."""
    keys: set = set()
    ids: set = set()
    for item in items or []:
        cid = _get(item, "candidate_id")
        if _truthy(cid):
            src = _get(item, "source")
            keys.add(f"{'' if src is None else _js_str(src)}:{_js_str(cid)}")
            ids.add(_js_str(cid))
        jd = _get(item, "jobdiva_candidate_id")
        if _truthy(jd):
            ids.add(_js_str(jd))
    return {"keys": keys, "ids": ids}


