# ── JavaScript semantics ────────────────────────────────────────────────────

# JS WhiteSpace + LineTerminator (String.prototype.trim and regex \s).
_JS_WS_CHARS = (
    "\t\n\x0b\x0c\r \xa0\u1680\u2000\u2001\u2002\u2003\u2004\u2005\u2006"
    "\u2007\u2008\u2009\u200a\u2028\u2029\u202f\u205f\u3000\ufeff"
)
_WS = "\t\n\x0b\x0c\r \xa0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff"  # class body
_WS_RUN_RE = re.compile("[" + _WS + "]+")
_NON_DIGIT_RE = re.compile(r"[^0-9]")


def _truthy(v: Any) -> bool:
    if v.__class__ is str:
        return v != ""
    if v is None or v is False:
        return False
    if v is True:
        return True
    if isinstance(v, (int, float)):
        return v == v and v != 0  # NaN and 0 are falsy
    if isinstance(v, str):
        return v != ""
    return True  # lists and dicts are truthy in JS, even when empty


def _or(*vals: Any) -> Any:
    """``a || b || c``: the first truthy operand, else the last one."""
    for v in vals[:-1]:
        if _truthy(v):
            return v
    return vals[-1]


def _is_number(v: Any) -> bool:
    """``typeof v === "number"``."""
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _get(o: Any, key: str) -> Any:
    """``o?.key`` for JSON values: a non-object (or missing key) → None."""
    if o.__class__ is dict or isinstance(o, dict):
        return o.get(key)
    return None


def _js_num_str(x: float) -> str:
    """Number.prototype.toString() for a double."""
    if x != x:
        return "NaN"
    if x == math.inf:
        return "Infinity"
    if x == -math.inf:
        return "-Infinity"
    if x == 0:
        return "0"
    if x < 0:
        return "-" + _js_num_str(-x)
    if float(x).is_integer() and x < 1e21:
        return str(int(x))
    s = repr(float(x))  # shortest round-trip digits
    mant, _, exp = s.partition("e")
    e = int(exp) if exp else 0
    ip, _, fp = mant.partition(".")
    digits = ip + fp
    n = len(ip) + e
    stripped = digits.lstrip("0")
    n -= len(digits) - len(stripped)
    digits = stripped.rstrip("0") or "0"
    k = len(digits)
    if k <= n <= 21:
        return digits + "0" * (n - k)
    if 0 < n <= 21:
        return digits[:n] + "." + digits[n:]
    if -6 < n <= 0:
        return "0." + "0" * (-n) + digits
    sign = "+" if n - 1 >= 0 else "-"
    head = digits if k == 1 else digits[0] + "." + digits[1:]
    return f"{head}e{sign}{abs(n - 1)}"


def _js_str(v: Any) -> str:
    """``String(v)`` (``None`` → "null"; callers guard ``undefined``)."""
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, str):
        return v
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return _js_num_str(v)
    if isinstance(v, (list, tuple)):
        return ",".join("" if x is None else _js_str(x) for x in v)
    if isinstance(v, dict):
        return "[object Object]"
    return str(v)


def _s(v: Any) -> str:
    """``String(v || "")``."""
    if v.__class__ is str:
        return v
    return _js_str(v) if _truthy(v) else ""


def _js_trim(s: str) -> str:
    return s.strip(_JS_WS_CHARS)


def _js_len(s: str) -> int:
    """``s.length`` (UTF-16 code units)."""
    if s.isascii():
        return len(s)
    return len(s) + sum(1 for ch in s if ord(ch) > 0xFFFF)


_JS_DECIMAL_RE = re.compile(r"[+-]?(?:[0-9]+\.?[0-9]*|\.[0-9]+)(?:[eE][+-]?[0-9]+)?")
_JS_RADIX_LITERALS = (
    (re.compile(r"0[xX][0-9a-fA-F]+"), 16),
    (re.compile(r"0[oO][0-7]+"), 8),
    (re.compile(r"0[bB][01]+"), 2),
)


def _js_to_number(v: Any) -> float:
    """``Number(v)`` for JSON values (``None`` → 0, as ``Number(null)``)."""
    if v is None or v is False:
        return 0.0
    if v is True:
        return 1.0
    if isinstance(v, (int, float)):
        try:
            return float(v)
        except OverflowError:
            return math.inf if v > 0 else -math.inf
    if isinstance(v, (list, tuple)):
        return _js_to_number(_js_str(v))
    if not isinstance(v, str):
        return math.nan
    t = _js_trim(v)
    if t == "":
        return 0.0
    if t in ("Infinity", "+Infinity"):
        return math.inf
    if t == "-Infinity":
        return -math.inf
    for pattern, base in _JS_RADIX_LITERALS:
        if pattern.fullmatch(t):
            return float(int(t[2:], base))
    if t[:2].lower() in ("0x", "0o", "0b"):
        return math.nan
    if _JS_DECIMAL_RE.fullmatch(t):
        return float(t)
    return math.nan


def _set_has(s: Any, v: Any) -> bool:
    """``set.has(v)`` with JS SameValueZero against a set of string ids."""
    if v is None or isinstance(v, (bool, dict, list)):
        return False
    try:
        return v in s
    except TypeError:
        return False


def _unique(items: Iterable[Any]) -> list:
    return list(dict.fromkeys(items))


def _reject_constant(name: str) -> Any:
    raise ValueError(f"not JSON: {name}")


def _json_parse(s: str) -> Any:
    """``JSON.parse``: no NaN / Infinity tokens."""
    return json.loads(s, parse_constant=_reject_constant)


# ── Contact validity ────────────────────────────────────────────────────────

_LAUNCH_EMAIL_RE = re.compile("[^@" + _WS + "]+@[^@" + _WS + r"]+\.[^@" + _WS + "]+")


def is_valid_launch_email(value: Any) -> bool:
    email = _js_trim(_s(value)).lower()
    if not email or not _LAUNCH_EMAIL_RE.fullmatch(email):
        return False
    if email in PLACEHOLDER_LAUNCH_EMAILS:
        return False
    if email.endswith("@example.com"):
        return False
    if email.endswith("@noemail.pair.ai"):
        return False
    # JobDiva's synthetic Auto_<id>@jobdiva.com addresses are dead.
    if email.endswith("@jobdiva.com"):
        return False
    return True


def launch_phone_digits(value: Any) -> str:
    return _NON_DIGIT_RE.sub("", _s(value))


def is_valid_launch_phone(value: Any) -> bool:
    return len(launch_phone_digits(value)) >= 7


def normalize_dnc_phone(raw: Any) -> Optional[str]:
    """lib/phone.ts normalizePhone (== utils/phone.py normalize_phone)."""
    if raw is None:
        return None
    digits = _NON_DIGIT_RE.sub("", _js_str(raw))
    if not digits:
        return None
    if len(digits) == 10:
        return "1" + digits
    if len(digits) == 11 and digits.startswith("1"):
        return digits
    return None


def better_phone_ui(current: Any, incoming: Any) -> str:
    """A streamed phone never downgrades a valid number to an empty/invalid one."""
    cur = _js_trim(_s(current))
    inc = _js_trim(_s(incoming))
    if not inc:
        return cur
    if normalize_dnc_phone(inc) is None and normalize_dnc_phone(cur) is not None:
        return cur
    return inc


def get_candidate_launch_email(c: Any) -> str:
    ei = _get(c, "enhanced_info")
    d = _get(c, "data")
    dei = _get(d, "enhanced_info")
    z = _get(d, "zoominfo_contact_enrichment")
    v = _or(
        _get(c, "email"), _get(c, "workEmail"), _get(c, "personalEmail"),
        _get(ei, "email"), _get(ei, "workEmail"), _get(ei, "personalEmail"),
        _get(d, "email"), _get(d, "workEmail"), _get(d, "personalEmail"),
        _get(dei, "email"), _get(dei, "workEmail"), _get(dei, "personalEmail"),
        _get(z, "workEmail"), _get(z, "personalEmail"),
        "",
    )
    return _js_trim(_js_str(v)).lower()


def get_candidate_launch_phone(c: Any) -> str:
    """The candidate's personal number: the first NON-EMPTY phone field that
    is not a work number an earlier lookup saved (validity is not checked)."""
    d = _get(c, "data")
    enrich = _or(_get(d, "zoominfo_contact_enrichment"), {})

    def digits(v: Any) -> str:
        return _NON_DIGIT_RE.sub("", _s(v))

    saved_work = digits(_get(enrich, "workPhone"))
    saved_mobile = digits(_get(enrich, "mobilePhone"))

    def is_saved_work_number(v: Any) -> bool:
        return bool(saved_work) and digits(v) == saved_work and digits(v) != saved_mobile

    ei = _get(c, "enhanced_info")
    dei = _get(d, "enhanced_info")
    options = [
        _get(c, "phone"), _get(c, "mobilePhone"),
        _get(ei, "phone"), _get(ei, "mobilePhone"),
        _get(d, "phone"), _get(d, "mobilePhone"),
        _get(dei, "phone"), _get(dei, "mobilePhone"),
        _get(enrich, "mobilePhone"),
    ]
    for v in options:
        if _js_trim(_s(v)) and not is_saved_work_number(v):
            return _js_trim(_js_str(v))
    return ""


def is_launchable_now(c: Any) -> bool:
    return is_valid_launch_phone(get_candidate_launch_phone(c)) or is_valid_launch_email(
        get_candidate_launch_email(c)
    )


# ── Display name ────────────────────────────────────────────────────────────

_ANONYMOUS_NAMES = ("linkedin candidate", "professional candidate", "unknown candidate", "unknown")


def get_candidate_display_name(c: Any) -> str:
    def normalize(value: Any) -> str:
        text = value if isinstance(value, str) else _s(value)
        cleaned = _js_trim(_WS_RUN_RE.sub(" ", text))
        if not cleaned:
            return ""
        if cleaned.lower() in _ANONYMOUS_NAMES:
            return ""
        return cleaned

    full_name = normalize(_get(c, "name"))
    if full_name:
        return full_name
    parts = [_get(c, "firstName"), _get(c, "lastName")]
    composed = normalize(" ".join(_js_str(p) for p in parts if _truthy(p)))
    if composed:
        return composed
    title = normalize(_get(c, "title"))
    if title:
        return title
    return "LinkedIn profile" if _get(c, "source") == "LinkedIn" else "Unnamed candidate"


# ── Cross-source de-dup ─────────────────────────────────────────────────────

_MERGE_FILL_FIELDS = (
    "phone", "location", "city", "state", "title", "headline",
    "resume_id", "profile_url", "linkedin_url", "image_url", "experience_years",
    "jobdiva_candidate_id", "jobdiva_id",
)
_TRAILING_SLASHES_RE = re.compile(r"/+\Z")


def is_placeholder_email_ui(e: Any) -> bool:
    n = _js_trim(_s(e)).lower()
    if not n or "@" not in n:
        return True
    domain = n.split("@")[-1]
    if domain == "jobdiva.com":
        return True
    if n.endswith("@noemail.pair.ai"):
        return True
    return False


def cand_is_jobdiva_ui(c: Any) -> bool:
    if _s(_get(c, "source")).lower().startswith("jobdiva"):
        return True
    srcs = _get(c, "sources")
    if isinstance(srcs, list) and any(_s(x).lower().startswith("jobdiva") for x in srcs):
        return True
    jd = _or(_get(c, "jobdiva_candidate_id"), _get(c, "jobdiva_id"),
             _get(_get(c, "data"), "jobdiva_candidate_id"))
    return bool(_js_trim(_s(jd)))


def _dedupe_email(c: Any) -> str:
    e = _js_trim(_s(_or(_get(c, "email"), _get(_get(c, "data"), "email"),
                        _get(_get(c, "enhanced_info"), "email")))).lower()
    return e if e and not is_placeholder_email_ui(e) else ""


def _dedupe_phone(c: Any) -> str:
    p = _or(_get(c, "phone"), _get(_get(c, "data"), "phone"), _get(_get(c, "enhanced_info"), "phone"))
    digits = _NON_DIGIT_RE.sub("", _s(p))
    if len(digits) < 7:
        return ""
    # A shared/placeholder line (000-000-0000, 555-555-5555) must not collapse rows.
    if len(set(digits)) < 4:
        return ""
    return digits[-10:]


def _dedupe_name(c: Any) -> str:
    f = _js_trim(_s(_get(c, "firstName")).lower())
    l = _js_trim(_s(_get(c, "lastName")).lower())
    full = _js_trim(f"{f} {l}")
    return full or _js_trim(_s(_get(c, "name")).lower())


def _dedupe_linkedin(c: Any) -> str:
    u = _js_trim(_s(_or(_get(c, "profile_url"), _get(_get(_get(c, "data"), "urls"), "linkedin"),
                        _get(c, "linkedin_url")))).lower()
    return _TRAILING_SLASHES_RE.sub("", u.split("?")[0]) if "linkedin.com" in u else ""


def dedupe_keys(c: Any) -> list:
    """The strong identity keys two rows of one person share."""
    keys = []
    email = _dedupe_email(c)
    if email:
        keys.append(f"email:{email}")
    phone = _dedupe_phone(c)
    name = _dedupe_name(c)
    if phone and name and " " in name:
        keys.append(f"phone-name:{phone}|{name}")
    li = _dedupe_linkedin(c)
    if li:
        keys.append(f"linkedin:{li}")
    return keys


def _assign_like_js(dst: dict, src: dict, key: str) -> None:
    """``dst[key] = src[key]`` where a missing key is ``undefined`` (omitted)."""
    if key in src:
        dst[key] = src[key]
    else:
        dst.pop(key, None)


def merge_best_of(dst: dict, src: dict) -> dict:
    """Fold ``src``'s best info into ``dst`` (mutates and returns ``dst``)."""

    def src_list(c: dict) -> list:
        out = []
        sources = c.get("sources")
        if isinstance(sources, list):
            out.extend(_js_str(x) for x in sources if _truthy(x))
        if _truthy(c.get("source")):
            out.append(_js_str(c.get("source")))
        return out

    merged = _unique(src_list(dst) + src_list(src))
    if merged:
        dst["sources"] = merged
    for f in _MERGE_FILL_FIELDS:
        if not _truthy(dst.get(f)) and _truthy(src.get(f)):
            dst[f] = src[f]
    # No-contact and hiring-client conflict are sticky-true across merges.
    if src.get("no_contact") is True and dst.get("no_contact") is not True:
        dst["no_contact"] = True
        _assign_like_js(dst, src, "no_contact_reason")
        _assign_like_js(dst, src, "no_contact_company")
    if src.get("client_conflict") is True and dst.get("client_conflict") is not True:
        dst["client_conflict"] = True
        _assign_like_js(dst, src, "client_conflict_reason")
        _assign_like_js(dst, src, "client_conflict_company")
        _assign_like_js(dst, src, "client_conflict_relation")
    d_email = _s(dst.get("email"))
    s_email = _s(src.get("email"))
    if s_email and s_email != d_email and (
        not d_email or (is_placeholder_email_ui(d_email) and not is_placeholder_email_ui(s_email))
    ):
        dst["email"] = s_email

    def bad_resume(r: Any) -> bool:
        text = _s(r)
        return not _js_trim(text) or "Resume content unavailable" in text

    d_r = _s(dst.get("resume_text"))
    s_r = _s(src.get("resume_text"))
    if s_r and not bad_resume(s_r) and (bad_resume(d_r) or _js_len(s_r) > _js_len(d_r)):
        dst["resume_text"] = src.get("resume_text")
    return dst


def _source_prio(s: Any) -> int:
    low = _s(s).lower()
    if "applicant" in low:
        return 1
    if "talentsearch" in low:
        return 2
    return 3


def resolve_absorbed(absorbed: dict, rows: Iterable[Any]) -> dict:
    """The final view of a ``deduplicate_candidates_ui(..., absorbed=)`` map:
    every loser pointed at its LAST survivor (a survivor can itself be merged
    away later), minus ids that are ``rows`` again (re-added after a drop).
    Returns a new dict; ``absorbed`` is not modified."""
    present = {candidate_row_id(row) for row in rows}
    out = {}
    for loser, target in absorbed.items():
        if loser in present:
            continue
        visited = {loser}
        while target in absorbed and target not in present and target not in visited:
            visited.add(target)
            target = absorbed[target]
        out[loser] = target
    return out


def deduplicate_candidates_ui(
    candidates: list, keys_cache: Optional[dict] = None, absorbed: Optional[dict] = None,
) -> list:
    """Collapse rows of the same person (``deduplicateCandidatesUI``).

    Same output as the TS (row order included: a merged survivor moves to the
    end), but matches through a key → row index instead of re-scanning every
    kept row, so a call is O(rows × keys) rather than O(rows²).

    ``keys_cache`` (optional, owned by the caller, e.g. one dict per search
    run) memoises each row's keys across calls by object identity; it is
    pruned to the returned rows on every call. Only valid while rows are
    treated as immutable — which every function here does (patches and
    merges build new dicts). ``StreamRun`` owns one for you.

    ``absorbed`` (optional out-parameter, Python only — not a browser rule):
    every merge records ``loser row id → survivor row id``
    (``candidate_row_id``; same-id merges are not recorded). Accumulate one
    dict across calls (``StreamRun`` does) and read it through
    ``resolve_absorbed(absorbed, final_rows)`` for who ended up folded into
    whom — the server records those as ``identity_duplicate:<survivor_id>``.
    """
    entries: dict = {}  # seq → row; insertion order == the TS uniqueResults order
    keys_by_seq: dict = {}
    index: dict = {}  # key → {seq}
    next_seq = 0

    def keys_of(row: Any) -> list:
        if keys_cache is None:
            return dedupe_keys(row)
        hit = keys_cache.get(id(row))
        if hit is not None and hit[0] is row:
            return hit[1]
        return dedupe_keys(row)

    def push(row: Any, keys: list) -> None:
        nonlocal next_seq
        entries[next_seq] = row
        keys_by_seq[next_seq] = keys
        for k in keys:
            index.setdefault(k, set()).add(next_seq)
        next_seq += 1

    for cand in candidates:
        c_keys = keys_of(cand)
        if not c_keys:
            push(cand, c_keys)
            continue
        matched: set = set()
        for k in c_keys:
            matched |= index.get(k, set())
        if not matched:
            push(cand, c_keys)
            continue
        match_seqs = sorted(matched)
        competitors = [cand] + [entries[s] for s in match_seqs]
        # JobDiva-bearing row always survives; then has-both-contacts, then
        # source priority, then match_score.
        winner = competitors[0]
        for comp in competitors[1:]:
            w_jd = cand_is_jobdiva_ui(winner)
            c_jd = cand_is_jobdiva_ui(comp)
            if c_jd != w_jd:
                if c_jd:
                    winner = comp
                continue
            w_both = bool(_dedupe_email(winner)) and bool(_dedupe_phone(winner))
            c_both = bool(_dedupe_email(comp)) and bool(_dedupe_phone(comp))
            if c_both != w_both:
                if c_both:
                    winner = comp
                continue
            w_prio = _source_prio(_get(winner, "source"))
            c_prio = _source_prio(_get(comp, "source"))
            if c_prio != w_prio:
                if c_prio < w_prio:
                    winner = comp
                continue
            if _js_to_number(_or(_get(comp, "match_score"), 0)) > _js_to_number(
                _or(_get(winner, "match_score"), 0)
            ):
                winner = comp
        survivor = dict(winner)
        for comp in competitors:
            if comp is not winner:
                merge_best_of(survivor, comp)
        if absorbed is not None:
            win_id = candidate_row_id(winner)
            for comp in competitors:
                lose_id = candidate_row_id(comp) if comp is not winner else ""
                if win_id and lose_id and lose_id != win_id:
                    absorbed[lose_id] = win_id
        for s in match_seqs:
            for k in keys_by_seq.pop(s):
                index[k].discard(s)
            del entries[s]
        push(survivor, dedupe_keys(survivor))
    if keys_cache is not None:
        # Holding the row keeps its id() from being reused while cached.
        keys_cache.clear()
        keys_cache.update({id(row): (row, keys_by_seq[s]) for s, row in entries.items()})
    return list(entries.values())


